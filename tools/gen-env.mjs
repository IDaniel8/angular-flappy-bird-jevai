/**
 * Reads `.env` and writes `src/environments/env.generated.ts`.
 *
 * Why not a builder plugin: @ngx-env/builder@22 injects variables for `ng build`
 * but not for `ng serve` (it patches an architect hook Angular 22.2 no longer
 * calls), so the app would silently run with an empty key in development.
 * Generating a plain TS module works identically for serve, build and watch.
 *
 * Runs automatically via the prestart / prebuild / postinstall npm scripts.
 */
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const envFile = resolve(root, '.env');
const outFile = resolve(root, 'src/environments/env.generated.ts');

if (existsSync(envFile)) {
  // Node 24 can parse .env files natively — no dotenv dependency needed.
  process.loadEnvFile(envFile);
}

const apiKey = (process.env['NG_APP_OPENROUTER_KEY'] ?? '').trim();

const contents = `// AUTO-GENERATED by tools/gen-env.mjs — do not edit, do not commit.
// Values come from the git-ignored .env file.
export const ENV = {
  openRouterKey: ${JSON.stringify(apiKey)},
} as const;
`;

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, contents, 'utf8');

console.log(
  `[env] src/environments/env.generated.ts written — OpenRouter key ${apiKey ? 'found' : 'MISSING (set NG_APP_OPENROUTER_KEY in .env)'}`,
);
